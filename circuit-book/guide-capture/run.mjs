/**
 * Rebuilds every guide screenshot from the current code.
 *
 *   npm run guide:capture              build, capture, write images + figures.ts
 *   npm run guide:capture -- --no-build reuse the last capture build (.next-guide)
 *
 * Steps: build the app pointed at the local mock Supabase, start both servers,
 * drive the real pages with Playwright (capture.mjs), then write the images to
 * public/guide/shots (content-hashed names, so phones never show a stale one)
 * and regenerate src/app/guide/figures.ts, which the Guide page and the tour
 * read. CI runs this on every push; see .github/workflows/circuit-book-guide.yml.
 *
 * Set CB_CHROMIUM_PATH to use an already-installed Chromium instead of the
 * one `npx playwright install chromium` downloads.
 */
import { spawn, spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { startMock } from "./mock-supabase.mjs";
import { capture } from "./capture.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP = path.resolve(HERE, "..");
const SHOTS_DIR = path.join(APP, "public/guide/shots");
const FIGURES_TS = path.join(APP, "src/app/guide/figures.ts");
const NEXT = path.join(APP, "node_modules/next/dist/bin/next");

const MOCK_PORT = 54329;
const APP_PORT = 3949;
const MOCK = `http://127.0.0.1:${MOCK_PORT}`;
const BASE = `http://127.0.0.1:${APP_PORT}`;

const env = {
  ...process.env,
  NEXT_PUBLIC_SUPABASE_URL: MOCK,
  NEXT_PUBLIC_SUPABASE_ANON_KEY: "guide-capture-anon-key",
  NEXT_TELEMETRY_DISABLED: "1",
  CB_GUIDE_CAPTURE: "1", // own build folder, no type check: see next.config.ts
};

async function waitFor(url, ms = 60000) {
  const until = Date.now() + ms;
  while (Date.now() < until) {
    try {
      const r = await fetch(url, { redirect: "manual" });
      if (r.status < 500) return;
    } catch {
      /* not up yet */
    }
    await new Promise((r) => setTimeout(r, 500));
  }
  throw new Error(`Timed out waiting for ${url}`);
}

const ts = (v) => JSON.stringify(v, null, 2).replace(/\n/g, "\n  ");

/** A server left over from an earlier run would get screenshotted instead of this build. */
async function assertFree(url) {
  const up = await fetch(url).then(() => true, () => false);
  if (up) throw new Error(`Something is already listening at ${url}. Stop it and run again.`);
}

async function main() {
  await assertFree(BASE);
  await assertFree(MOCK);
  if (!process.argv.includes("--no-build")) {
    console.log("Building the app against the mock backend…");
    // next build adds the capture build folder to tsconfig.json; put it back.
    const tsconfig = path.join(APP, "tsconfig.json");
    const before = fs.readFileSync(tsconfig, "utf8");
    const b = spawnSync(process.execPath, [NEXT, "build"], { cwd: APP, env, stdio: "inherit" });
    fs.writeFileSync(tsconfig, before);
    if (b.status !== 0) throw new Error("next build failed");
  }

  const mock = await startMock(MOCK_PORT);
  const app = spawn(process.execPath, [NEXT, "start", "-p", String(APP_PORT), "-H", "127.0.0.1"], {
    cwd: APP, env, stdio: ["ignore", "inherit", "inherit"],
  });

  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "cb-guide-"));
  try {
    await waitFor(`${BASE}/login`);
    console.log("Capturing screens…");
    const manifest = await capture({ base: BASE, mock: MOCK, outDir: tmp, chromiumPath: process.env.CB_CHROMIUM_PATH });

    fs.mkdirSync(SHOTS_DIR, { recursive: true });
    const keep = new Set();
    const figures = {};
    for (const [name, entry] of Object.entries(manifest)) {
      const webp = await sharp(path.join(tmp, `${name}.png`)).webp({ quality: 80, effort: 6 }).toBuffer();
      const hash = crypto.createHash("sha1").update(webp).digest("hex").slice(0, 10);
      const file = `${name}.${hash}.webp`;
      fs.writeFileSync(path.join(SHOTS_DIR, file), webp);
      keep.add(file);
      figures[name] = {
        src: `/guide/shots/${file}`,
        width: entry.width,
        height: entry.height,
        title: entry.title,
        route: entry.route,
        focus: entry.focus,
        legend: entry.legend,
      };
    }
    for (const f of fs.readdirSync(SHOTS_DIR)) if (!keep.has(f)) fs.unlinkSync(path.join(SHOTS_DIR, f));

    const body = Object.entries(figures).map(([k, v]) => `  ${JSON.stringify(k)}: ${ts(v)},`).join("\n");
    fs.writeFileSync(
      FIGURES_TS,
      `/**
 * GENERATED by guide-capture/run.mjs — do not edit by hand.
 * Run \`npm run guide:capture\` after changing a screen; CI does it on every push.
 *
 * One entry per annotated screenshot: legend entries match the numbered
 * callouts drawn on the image, in order; \`focus\` is the band (in CSS px) the
 * tour zooms in on; \`route\` is the app page shown, for the coverage check.
 */

export type Figure = {
  src: string;
  width: number;
  height: number;
  title: string;
  route: string;
  focus: { y: number; height: number };
  legend: [label: string, text: string][];
};

export const FIGURES = {
${body}
} satisfies Record<string, Figure>;

export type FigureName = keyof typeof FIGURES;
`,
    );
    console.log(`Wrote ${keep.size} screenshots and src/app/guide/figures.ts`);
  } finally {
    app.kill();
    mock.close();
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
